#!/usr/bin/env python3
"""Writes docs/grammar.ebnf: the entire grammar, as `help grammar` prints it in a running game.

    python3 tools/grammar.py --game-dir <run dir>

Run it against a client with Sable installed (the 1.21.1 NeoForge dev client), so the sable: productions are in the
file, then `./gradlew grammarDiagrams` to redraw docs/grammar.xhtml.
"""
import argparse
import json
import os
import sys

from smoke_test import run

HEADER = ("/* The entire grammar of Blockpilot's command language: the core productions, then one production per "
          "command and option, as `help grammar` prints them. Generated by tools/grammar.py; don't edit by hand. */")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--game-dir", default="run")
    parser.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "docs", "grammar.ebnf"))
    args = parser.parse_args()
    code, output = run(args.game_dir, "help grammar", as_json=True)
    if code != 0:
        print(output, file=sys.stderr)
        return 1
    rows = json.loads(output.splitlines()[0])["results"][0]["rows"]
    lines = [HEADER]
    previous = None
    for row in rows:
        # A blank line before the commands' section and between commands.
        if row["key"] != previous and row["key"] != "core":
            lines.append("")
        lines.append(row["ebnf"])
        previous = row["key"]
    with open(args.out, "w", encoding="utf-8") as target:
        target.write("\n".join(lines) + "\n")
    print(f"{os.path.normpath(args.out)}: {len(rows)} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
